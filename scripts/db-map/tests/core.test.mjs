import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { chmod, mkdtemp, mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { assertCatalogSqlByteOrdering, normalizeCatalog, parseCatalogCsv } from '../catalog.mjs';
import { CONFIG } from '../config.mjs';
import { assertAdapterFidelity, toTblsSchema, validateAgainstOfficialSchema, verifyVendoredSchema } from '../adapter.mjs';
import { enumeratePopulation } from '../population.mjs';
import { scannerRuntime, scanRepository } from '../scanner.mjs';
import { listFiles } from '../generate.mjs';
import { compareBytes, relationKey, stableJson } from '../util.mjs';
import { fixtureCsv } from './fixture.mjs';

const HERE = dirname(fileURLToPath(import.meta.url));
const REPO = resolve(HERE, '../../..');
let checks = 0;
function check(condition, message) { checks += 1; assert.ok(condition, message); }

const catalog = parseCatalogCsv(fixtureCsv());
const typescriptRuntime = await scannerRuntime();
check(typescriptRuntime.version === CONFIG.runtime.typescriptVersion && typescriptRuntime.sha256 === CONFIG.runtime.typescriptSha256, 'scanner loads the pinned TypeScript implementation');
check(catalog.relations.length === 7, 'fixture relation population');
check(catalog.columns.length === 9, 'fixture column population');
check(relationKey('a.b', 'c') === 'a%2Eb.c', 'dotted schema identifier is escaped canonically');
check(relationKey('a', 'b.c') === 'a.b%2Ec', 'dotted relation identifier is escaped canonically');
check(relationKey('a.b', 'c') !== relationKey('a', 'b.c'), 'dotted identifier tuples do not collide');
check(relationKey('a%2Eb', 'c') !== relationKey('a.b', 'c'), 'literal escape sequences do not collide');
const nonAsciiKeys = ['\u{10000}', '\uE000'];
check([...nonAsciiKeys].sort(compareBytes).join('|') === '\uE000|\u{10000}', 'UTF-8 byte ordering is explicit for non-ASCII strings');
const nonAsciiJson = stableJson({ [nonAsciiKeys[0]]: 1, [nonAsciiKeys[1]]: 2 });
check(nonAsciiJson.indexOf('\uE000') < nonAsciiJson.indexOf('\u{10000}'), 'canonical JSON keys use UTF-8 byte ordering');
const orderRoot = await mkdtemp(join(tmpdir(), 'db-map-order-'));
try {
  await writeFile(join(orderRoot, nonAsciiKeys[0]), 'supplementary');
  await writeFile(join(orderRoot, nonAsciiKeys[1]), 'private-use');
  check((await listFiles(orderRoot)).join('|') === '\uE000|\u{10000}', 'generated artifact paths use UTF-8 byte ordering');
} finally {
  await rm(orderRoot, { recursive: true, force: true });
}
check(catalog.relations.find((row) => row.key === 'public.parents').estimated_rows.state === 'unknown', 'negative estimates are unknown');
check(catalog.relations.find((row) => row.key === 'public.user_view').size_applicable === false, 'views have no table size');
check(catalog.logical_rollups[0].unknown_row_child_count === 1, 'partition rollup preserves unknown child count');
check(catalog.physical_totals.known_total_bytes === 52, 'physical totals exclude partition parent and view');
const emptyPolicies = parseCatalogCsv(fixtureCsv({ policies: [] }));
check(emptyPolicies.policies.length === 0, 'an explicitly present empty section is accepted');

const tbls = toTblsSchema(catalog);
check(assertAdapterFidelity(catalog, tbls), 'tbls adapter fidelity');
const publicUsers = tbls.tables.find((row) => row.name === 'public.users');
check(publicUsers.columns[1].default === "'none'::text", 'column default is mapped');
check(publicUsers.columns[0].extra_def === 'GENERATED BY DEFAULT AS IDENTITY', 'identity is mapped');
check(publicUsers.columns[2].extra_def === 'GENERATED ALWAYS AS STORED', 'generated marker is mapped');
check(publicUsers.constraints.map((row) => row.type).sort().join(',') === 'CHECK,FOREIGN KEY,PRIMARY KEY,UNIQUE', 'all constraint classes are mapped');
check(tbls.relations.length === 1 && tbls.relations[0].parent_table === 'auth.users', 'FK relation is mapped');
check(tbls.tables.some((row) => row.name === 'a%2Eb.c') && tbls.tables.some((row) => row.name === 'a.b%2Ec'), 'unsafe identifiers survive the tbls adapter distinctly');
const orderingCatalog = structuredClone(catalog);
const relationTemplate = orderingCatalog.relations.find((row) => row.key === 'public.users');
for (const schema of nonAsciiKeys) orderingCatalog.relations.push({ ...structuredClone(relationTemplate), schema, name: 'ordered', key: relationKey(schema, 'ordered') });
for (const name of nonAsciiKeys) orderingCatalog.enums.push({ schema: 'public', name, label: 'value', sort_order: 1 });
const fkTemplate = orderingCatalog.constraints.find((row) => row.type === 'f');
for (const schema of nonAsciiKeys) orderingCatalog.constraints.push({ ...structuredClone(fkTemplate), name: `ordered-${schema}`, referenced_schema: schema, referenced_relation: 'ordered' });
const orderingTbls = toTblsSchema(orderingCatalog);
check(orderingTbls.enums.findIndex((row) => row.name === 'public.\uE000') < orderingTbls.enums.findIndex((row) => row.name === 'public.\u{10000}'), 'adapter enum groups use UTF-8 byte ordering');
check(orderingTbls.viewpoints.findIndex((row) => row.name === '\uE000 schema') < orderingTbls.viewpoints.findIndex((row) => row.name === '\u{10000} schema'), 'adapter schema viewpoints use UTF-8 byte ordering');
const crossSchemaTables = orderingTbls.viewpoints.find((row) => row.id === 'cross-schema-relations').tables;
check(crossSchemaTables.indexOf('\uE000.ordered') < crossSchemaTables.indexOf('\u{10000}.ordered'), 'adapter cross-schema tables use UTF-8 byte ordering');

const rawRelations = catalog.relations.map(({ key, estimated_rows, is_partition_child, parent, size_applicable, ...row }) => ({
  ...row,
  estimated_rows: estimated_rows.state === 'known' ? estimated_rows.value : null,
}));
const partitionTemplate = rawRelations.find((row) => row.name === 'parents');
const childTemplate = rawRelations.find((row) => row.name === 'users_2026');
const orderingSections = {
  meta: [catalog.meta], schemas: catalog.schemas, relations: [...rawRelations], columns: catalog.columns,
  constraints: catalog.constraints, indexes: catalog.indexes, partition_edges: [...catalog.partition_edges],
  policies: catalog.policies, enums: catalog.enums,
};
for (let i = 0; i < nonAsciiKeys.length; i += 1) {
  orderingSections.relations.push({ ...structuredClone(partitionTemplate), name: nonAsciiKeys[i] });
  orderingSections.relations.push({ ...structuredClone(childTemplate), name: `ordered_child_${i}` });
  orderingSections.partition_edges.push({ parent_schema: 'public', parent_relation: nonAsciiKeys[i], child_schema: 'public', child_relation: `ordered_child_${i}`, bound: `FOR VALUES IN (${i})` });
}
const orderingRollups = normalizeCatalog(orderingSections).logical_rollups.map((row) => row.parent);
check(orderingRollups.indexOf('public.\uE000') < orderingRollups.indexOf('public.\u{10000}'), 'logical partition rollups use UTF-8 byte ordering');
const officialSchema = await verifyVendoredSchema(resolve(HERE, '../vendor/tbls-v1.97.0.schema.json'));
validateAgainstOfficialSchema(tbls, officialSchema);
checks += 1;

const sql = await readFile(resolve(HERE, '../catalog.sql'), 'utf8');
check(assertCatalogSqlByteOrdering(sql), 'catalog SQL string ordering is pinned to byte collation');
check(!sql.includes('\\'), 'catalog SQL has no psql meta-command');
check((sql.match(/;/g) ?? []).length === 1, 'catalog extraction is exactly one SQL statement');
check(/SELECT section, section_order, row_order, payload::text AS payload_json/.test(sql), 'catalog stream has the versioned tagged shape');

const root = await mkdtemp(join(tmpdir(), 'db-map-scan-'));
try {
  await mkdir(join(root, 'shared'), { recursive: true });
  await mkdir(join(root, 'server'), { recursive: true });
  await writeFile(join(root, 'shared/schema.ts'), `import { pgTable } from 'drizzle-orm/pg-core';\nexport const users = pgTable('users', {});\n`);
  await writeFile(join(root, 'server/use.ts'), `import { users as accounts } from '../shared/schema';\nimport { Pool } from 'pg';\nconst pool = new Pool();\nawait db.select().from(accounts);\nawait db.insert(accounts).values({});\nawait pool.query('UPDATE auth.users SET id = id');\nawait pool.query('SELECT * FROM users');\nawait pool.query(\`DELETE FROM public.users WHERE id = \${id}\`);\n`);
  const constructorFixture = `import { Client, Pool } from 'pg';\nexport const client = new ` + `Client();\nexport const pool = new ` + `Pool();\n`;
  await writeFile(join(root, 'server/constructor.ts'), constructorFixture);
  await writeFile(join(root, 'helper'), `#!/bin/sh\ndt-sql-login <<'SQL'\nDELETE FROM public.users;\nSQL\n`);
  await writeFile(join(root, 'Dockerfile'), 'FROM node:20\n');
  const paths = ['Dockerfile', 'helper', 'server/constructor.ts', 'server/use.ts', 'shared/schema.ts'];
  const population = { sourceRef: 'a'.repeat(40), included: paths.map((path) => ({ path, mode: path === 'helper' ? '100755' : '100644', oid: 'b'.repeat(40), classifier: path === 'Dockerfile' ? 'root_dockerfile' : path === 'helper' ? 'shebang' : 'suffix', evidenceClass: 'runtime' })), excluded: [], includedTupleSha256: 'x', includedPathSha256: 'y', excludedPathSha256: 'z' };
  const scan = await scanRepository(root, population, catalog);
  check(scan.usage.some((row) => row.relation === 'public.users' && row.operation === 'read' && row.source === 'drizzle'), 'Drizzle alias read resolves');
  check(scan.usage.some((row) => row.relation === 'public.users' && row.operation === 'insert' && row.source === 'drizzle'), 'Drizzle alias insert resolves');
  check(scan.usage.some((row) => row.relation === 'auth.users' && row.operation === 'update'), 'qualified raw SQL resolves');
  check(scan.usage.some((row) => row.relation === 'public.users' && row.operation === 'delete' && row.file === 'helper'), 'extensionless helper SQL resolves');
  check(scan.unresolved.some((row) => row.kind === 'sql_relation' && row.detail.startsWith('ambiguous bare relation')), 'ambiguous bare SQL stays unresolved');
  check(scan.unresolved.some((row) => row.kind === 'dynamic_sql'), 'dynamic SQL stays unresolved');
  check(scan.helpers.some((row) => row.kind === 'node-postgres Pool'), 'direct Node login helper is inventoried');
  check(scan.helpers.some((row) => row.kind === 'dt-sql login'), 'dt-sql login helper is inventoried');
  const constructors = scan.helpers.filter((row) => row.file === 'server/constructor.ts');
  check(constructors.length === 2 && constructors.every((row) => row.operations.length === 0
    && row.unresolved.length === 1
    && row.unresolved[0].kind === 'helper_usage'
    && row.unresolved[0].helper_kind === row.kind
    && row.unresolved[0].detail.includes('requires hand resolution')),
  'each constructor-only helper in a multi-helper file gets its own explicit reason');
  check(scan.unresolved.filter((row) => row.file === 'server/constructor.ts' && row.kind === 'helper_usage').length === 2,
    'each constructor-only helper reason is also present in unresolved inventory');
} finally {
  await rm(root, { recursive: true, force: true });
}

try {
  execFileSync('git', ['-C', REPO, 'cat-file', '-e', '8130531b5089edbf080cb1de028b82dce77bec73^{commit}']);
  const audit = enumeratePopulation(REPO, '8130531b5089edbf080cb1de028b82dce77bec73');
  check(audit.included.length === 2363, `audit ref included population is ${audit.included.length}, wanted 2363`);
  check(audit.excluded.length === 103, `audit ref excluded population is ${audit.excluded.length}, wanted 103`);
  check(audit.included.filter((row) => row.classifier === 'shebang').length === 38, 'audit ref has 38 included shebang programs');
  check(audit.included.filter((row) => row.classifier === 'root_dockerfile').length === 1, 'audit ref includes root Dockerfile');
} catch (error) {
  if (!`${error.message}`.includes('Not a valid object') && !`${error.message}`.includes('bad object')) throw error;
  const head = enumeratePopulation(REPO, 'HEAD');
  check(head.included.some((row) => row.classifier === 'shebang'), 'shallow checkout positive control finds a shebang input');
  check(head.included.some((row) => row.classifier === 'root_dockerfile'), 'shallow checkout positive control finds root Dockerfile');
}

console.log(`db-map core: ${checks} checks passed`);
