import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { chmod, mkdtemp, mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseCatalogCsv } from '../catalog.mjs';
import { assertAdapterFidelity, toTblsSchema, validateAgainstOfficialSchema, verifyVendoredSchema } from '../adapter.mjs';
import { enumeratePopulation } from '../population.mjs';
import { scanRepository } from '../scanner.mjs';
import { fixtureCsv } from './fixture.mjs';

const HERE = dirname(fileURLToPath(import.meta.url));
const REPO = resolve(HERE, '../../..');
let checks = 0;
function check(condition, message) { checks += 1; assert.ok(condition, message); }

const catalog = parseCatalogCsv(fixtureCsv());
check(catalog.relations.length === 5, 'fixture relation population');
check(catalog.columns.length === 7, 'fixture column population');
check(catalog.relations.find((row) => row.key === 'public.parents').estimated_rows.state === 'unknown', 'negative estimates are unknown');
check(catalog.relations.find((row) => row.key === 'public.user_view').size_applicable === false, 'views have no table size');
check(catalog.logical_rollups[0].unknown_row_child_count === 1, 'partition rollup preserves unknown child count');
check(catalog.physical_totals.known_total_bytes === 52, 'physical totals exclude partition parent and view');
const emptyPolicies = parseCatalogCsv(fixtureCsv({ policies: [] }));
check(emptyPolicies.policies.length === 0, 'an explicitly present empty section is accepted');

const tbls = toTblsSchema(catalog);
check(assertAdapterFidelity(catalog, tbls), 'tbls adapter fidelity');
const publicUsers = tbls.tables.find((row) => row.name === 'public.users');
check(publicUsers.columns[1].default === "'none'::text", 'column default is mapped');
check(publicUsers.columns[0].extra_def === 'GENERATED BY DEFAULT AS IDENTITY', 'identity is mapped');
check(publicUsers.columns[2].extra_def === 'GENERATED ALWAYS AS STORED', 'generated marker is mapped');
check(publicUsers.constraints.map((row) => row.type).sort().join(',') === 'CHECK,FOREIGN KEY,PRIMARY KEY,UNIQUE', 'all constraint classes are mapped');
check(tbls.relations.length === 1 && tbls.relations[0].parent_table === 'auth.users', 'FK relation is mapped');
const officialSchema = await verifyVendoredSchema(resolve(HERE, '../vendor/tbls-v1.97.0.schema.json'));
validateAgainstOfficialSchema(tbls, officialSchema);
checks += 1;

const sql = await readFile(resolve(HERE, '../catalog.sql'), 'utf8');
check(!sql.includes('\\'), 'catalog SQL has no psql meta-command');
check((sql.match(/;/g) ?? []).length === 1, 'catalog extraction is exactly one SQL statement');
check(/SELECT section, section_order, row_order, payload::text AS payload_json/.test(sql), 'catalog stream has the versioned tagged shape');

const root = await mkdtemp(join(tmpdir(), 'db-map-scan-'));
try {
  await mkdir(join(root, 'shared'), { recursive: true });
  await mkdir(join(root, 'server'), { recursive: true });
  await writeFile(join(root, 'shared/schema.ts'), `import { pgTable } from 'drizzle-orm/pg-core';\nexport const users = pgTable('users', {});\n`);
  await writeFile(join(root, 'server/use.ts'), `import { users as accounts } from '../shared/schema';\nimport { Pool } from 'pg';\nconst pool = new Pool();\nawait db.select().from(accounts);\nawait db.insert(accounts).values({});\nawait pool.query('UPDATE auth.users SET id = id');\nawait pool.query('SELECT * FROM users');\nawait pool.query(\`DELETE FROM public.users WHERE id = \${id}\`);\n`);
  await writeFile(join(root, 'helper'), `#!/bin/sh\ndt-sql-login <<'SQL'\nDELETE FROM public.users;\nSQL\n`);
  await writeFile(join(root, 'Dockerfile'), 'FROM node:20\n');
  const paths = ['Dockerfile', 'helper', 'server/use.ts', 'shared/schema.ts'];
  const population = { sourceRef: 'a'.repeat(40), included: paths.map((path) => ({ path, mode: path === 'helper' ? '100755' : '100644', oid: 'b'.repeat(40), classifier: path === 'Dockerfile' ? 'root_dockerfile' : path === 'helper' ? 'shebang' : 'suffix', evidenceClass: 'runtime' })), excluded: [], includedTupleSha256: 'x', includedPathSha256: 'y', excludedPathSha256: 'z' };
  const scan = await scanRepository(root, population, catalog);
  check(scan.usage.some((row) => row.relation === 'public.users' && row.operation === 'read' && row.source === 'drizzle'), 'Drizzle alias read resolves');
  check(scan.usage.some((row) => row.relation === 'public.users' && row.operation === 'insert' && row.source === 'drizzle'), 'Drizzle alias insert resolves');
  check(scan.usage.some((row) => row.relation === 'auth.users' && row.operation === 'update'), 'qualified raw SQL resolves');
  check(scan.usage.some((row) => row.relation === 'public.users' && row.operation === 'delete' && row.file === 'helper'), 'extensionless helper SQL resolves');
  check(scan.unresolved.some((row) => row.kind === 'sql_relation' && row.detail.startsWith('ambiguous bare relation')), 'ambiguous bare SQL stays unresolved');
  check(scan.unresolved.some((row) => row.kind === 'dynamic_sql'), 'dynamic SQL stays unresolved');
  check(scan.helpers.some((row) => row.kind === 'node-postgres Pool'), 'direct Node login helper is inventoried');
  check(scan.helpers.some((row) => row.kind === 'dt-sql login'), 'dt-sql login helper is inventoried');
} finally {
  await rm(root, { recursive: true, force: true });
}

try {
  execFileSync('git', ['-C', REPO, 'cat-file', '-e', '8130531b5089edbf080cb1de028b82dce77bec73^{commit}']);
  const audit = enumeratePopulation(REPO, '8130531b5089edbf080cb1de028b82dce77bec73');
  check(audit.included.length === 2363, `audit ref included population is ${audit.included.length}, wanted 2363`);
  check(audit.excluded.length === 103, `audit ref excluded population is ${audit.excluded.length}, wanted 103`);
  check(audit.included.filter((row) => row.classifier === 'shebang').length === 38, 'audit ref has 38 included shebang programs');
  check(audit.included.filter((row) => row.classifier === 'root_dockerfile').length === 1, 'audit ref includes root Dockerfile');
} catch (error) {
  if (!`${error.message}`.includes('Not a valid object') && !`${error.message}`.includes('bad object')) throw error;
  const head = enumeratePopulation(REPO, 'HEAD');
  check(head.included.some((row) => row.classifier === 'shebang'), 'shallow checkout positive control finds a shebang input');
  check(head.included.some((row) => row.classifier === 'root_dockerfile'), 'shallow checkout positive control finds root Dockerfile');
}

console.log(`db-map core: ${checks} checks passed`);
