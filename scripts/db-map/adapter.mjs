import { readFile } from 'node:fs/promises';
import { CONFIG } from './config.mjs';
import { assert, relationKey, sha256 } from './util.mjs';

const RELATION_TYPES = { r: 'TABLE', p: 'PARTITIONED TABLE', v: 'VIEW', m: 'MATERIALIZED VIEW', f: 'FOREIGN TABLE' };
const CONSTRAINT_TYPES = { p: 'PRIMARY KEY', u: 'UNIQUE', c: 'CHECK', f: 'FOREIGN KEY' };

function extraDefinition(column) {
  const out = [];
  if (column.identity === 'a') out.push('GENERATED ALWAYS AS IDENTITY');
  if (column.identity === 'd') out.push('GENERATED BY DEFAULT AS IDENTITY');
  if (column.generated === 's') out.push('GENERATED ALWAYS AS STORED');
  return out.join(' ');
}

export function toTblsSchema(catalog) {
  const columns = new Map();
  const indexes = new Map();
  const constraints = new Map();
  for (const row of catalog.columns) {
    const key = relationKey(row.schema, row.relation);
    if (!columns.has(key)) columns.set(key, []);
    const value = { name: row.name, type: row.type, nullable: Boolean(row.nullable) };
    if (row.default !== null) value.default = String(row.default);
    const extra = extraDefinition(row);
    if (extra) value.extra_def = extra;
    if (row.comment) value.comment = row.comment;
    columns.get(key).push(value);
  }
  for (const row of catalog.indexes) {
    const key = relationKey(row.schema, row.relation);
    if (!indexes.has(key)) indexes.set(key, []);
    const value = { name: row.name, def: row.definition, table: key, columns: row.columns };
    if (row.comment) value.comment = row.comment;
    indexes.get(key).push(value);
  }
  for (const row of catalog.constraints) {
    const key = relationKey(row.schema, row.relation);
    if (!constraints.has(key)) constraints.set(key, []);
    const value = { name: row.name, type: CONSTRAINT_TYPES[row.type] ?? row.type, def: row.definition, table: key, columns: row.columns };
    if (row.referenced_relation) {
      value.referenced_table = relationKey(row.referenced_schema, row.referenced_relation);
      value.referenced_columns = row.referenced_columns;
    }
    if (row.comment) value.comment = row.comment;
    constraints.get(key).push(value);
  }
  const tables = catalog.relations.map((row) => ({
    name: row.key,
    type: RELATION_TYPES[row.relkind] ?? row.relkind,
    ...(row.comment ? { comment: row.comment } : {}),
    columns: columns.get(row.key) ?? [],
    indexes: indexes.get(row.key) ?? [],
    constraints: constraints.get(row.key) ?? [],
  }));
  const relations = catalog.constraints.filter((row) => row.type === 'f').map((row) => ({
    table: relationKey(row.schema, row.relation),
    columns: row.columns,
    parent_table: relationKey(row.referenced_schema, row.referenced_relation),
    parent_columns: row.referenced_columns,
    def: row.definition,
  }));
  const enumGroups = new Map();
  for (const row of catalog.enums) {
    const key = relationKey(row.schema, row.name);
    if (!enumGroups.has(key)) enumGroups.set(key, []);
    enumGroups.get(key).push([Number(row.sort_order), row.label]);
  }
  const enums = [...enumGroups].sort().map(([name, values]) => ({ name, values: values.sort((a, b) => a[0] - b[0]).map((item) => item[1]) }));
  const schemaNames = [...new Set(catalog.relations.map((row) => row.schema))].sort();
  const viewpoints = schemaNames.map((schema) => ({
    id: `schema-${schema.replace(/[^A-Za-z0-9_-]/g, '-')}`,
    name: `${schema} schema`,
    desc: `All mapped relations in ${schema}.`,
    tables: catalog.relations.filter((row) => row.schema === schema).map((row) => row.key),
  }));
  const crossSchema = relations.filter((row) => row.table.split('.')[0] !== row.parent_table.split('.')[0]);
  viewpoints.push({
    id: 'cross-schema-relations',
    name: 'Cross-schema relations',
    desc: 'Relations participating in a foreign key across schema boundaries.',
    tables: [...new Set(crossSchema.flatMap((row) => [row.table, row.parent_table]))].sort(),
  });
  return {
    name: catalog.meta.database,
    desc: `DawnTrader catalog extracted ${catalog.meta.extracted_at_utc}.`,
    tables,
    relations,
    enums,
    driver: { name: 'postgres', database_version: String(catalog.meta.server_version_num) },
    viewpoints,
  };
}

function exactKeys(value, allowed, label) {
  for (const key of Object.keys(value)) assert(allowed.includes(key), `${label} has unsupported property ${key}`);
}

export function validateTblsSchema(schema) {
  exactKeys(schema, ['name', 'desc', 'tables', 'relations', 'functions', 'enums', 'driver', 'labels', 'viewpoints'], 'tbls schema');
  assert(Array.isArray(schema.tables), 'tbls schema tables must be an array');
  for (const table of schema.tables) {
    exactKeys(table, ['name', 'type', 'comment', 'columns', 'indexes', 'constraints', 'triggers', 'def', 'labels', 'referenced_tables'], `table ${table.name}`);
    assert(typeof table.name === 'string' && typeof table.type === 'string' && Array.isArray(table.columns), 'tbls table is missing a required property');
    for (const column of table.columns) {
      exactKeys(column, ['name', 'type', 'nullable', 'default', 'extra_def', 'labels', 'comment'], `column ${table.name}.${column.name}`);
      assert(typeof column.name === 'string' && typeof column.type === 'string' && typeof column.nullable === 'boolean', 'tbls column is missing a required property');
    }
    for (const index of table.indexes ?? []) assert(typeof index.name === 'string' && typeof index.def === 'string' && index.table === table.name && Array.isArray(index.columns), 'tbls index is incomplete');
    for (const constraint of table.constraints ?? []) assert(typeof constraint.name === 'string' && typeof constraint.type === 'string' && typeof constraint.def === 'string' && constraint.table === table.name, 'tbls constraint is incomplete');
  }
  for (const relation of schema.relations ?? []) assert(typeof relation.table === 'string' && Array.isArray(relation.columns) && typeof relation.parent_table === 'string' && Array.isArray(relation.parent_columns) && typeof relation.def === 'string', 'tbls relation is incomplete');
  return true;
}

function resolveRef(root, ref) {
  assert(ref.startsWith('#/'), `unsupported JSON Schema reference: ${ref}`);
  return ref.slice(2).split('/').reduce((value, key) => value[key.replaceAll('~1', '/').replaceAll('~0', '~')], root);
}

function schemaTypeMatches(value, type) {
  if (type === 'null') return value === null;
  if (type === 'array') return Array.isArray(value);
  if (type === 'object') return Boolean(value) && typeof value === 'object' && !Array.isArray(value);
  if (type === 'integer') return Number.isInteger(value);
  return typeof value === type;
}

function validateNode(value, node, root, path) {
  if (node.$ref) return validateNode(value, resolveRef(root, node.$ref), root, path);
  if (node.anyOf) {
    const errors = [];
    for (const choice of node.anyOf) {
      try { validateNode(value, choice, root, path); return; } catch (error) { errors.push(error.message); }
    }
    throw new Error(`${path} matches no anyOf branch: ${errors.join('; ')}`);
  }
  if (node.type) assert(schemaTypeMatches(value, node.type), `${path} is not ${node.type}`);
  if (node.enum) assert(node.enum.includes(value), `${path} is outside its enum`);
  if (node.type === 'object') {
    for (const key of node.required ?? []) assert(Object.hasOwn(value, key), `${path}.${key} is required by the official schema`);
    if (node.additionalProperties === false) for (const key of Object.keys(value)) assert(Object.hasOwn(node.properties ?? {}, key), `${path}.${key} is forbidden by the official schema`);
    for (const [key, child] of Object.entries(node.properties ?? {})) if (Object.hasOwn(value, key)) validateNode(value[key], child, root, `${path}.${key}`);
  }
  if (node.type === 'array') for (let i = 0; i < value.length; i += 1) validateNode(value[i], node.items, root, `${path}[${i}]`);
}

export function validateAgainstOfficialSchema(value, officialSchema) {
  validateNode(value, officialSchema, officialSchema, '$');
  return true;
}

export function assertAdapterFidelity(catalog, schema) {
  validateTblsSchema(schema);
  const tables = new Map(schema.tables.map((row) => [row.name, row]));
  assert(tables.size === catalog.relations.length, 'tbls relation set size differs from catalog');
  for (const relation of catalog.relations) assert(tables.has(relation.key), `tbls relation missing: ${relation.key}`);
  for (const relation of catalog.relations) {
    const table = tables.get(relation.key);
    const expectedColumns = catalog.columns.filter((row) => row.schema === relation.schema && row.relation === relation.name);
    assert(table.columns.length === expectedColumns.length, `tbls column set size differs for ${relation.key}`);
    for (let i = 0; i < expectedColumns.length; i += 1) {
      const source = expectedColumns[i];
      const target = table.columns[i];
      assert(target.name === source.name && target.type === source.type && target.nullable === Boolean(source.nullable), `tbls column identity differs: ${relation.key}.${source.name}`);
      assert((target.default ?? null) === (source.default === null ? null : String(source.default)), `tbls default differs: ${relation.key}.${source.name}`);
      assert((target.extra_def ?? '') === extraDefinition(source), `tbls identity/generated definition differs: ${relation.key}.${source.name}`);
    }
    const expectedConstraints = catalog.constraints.filter((row) => row.schema === relation.schema && row.relation === relation.name);
    assert((table.constraints ?? []).length === expectedConstraints.length, `tbls constraint set size differs for ${relation.key}`);
    for (const source of expectedConstraints) {
      const target = table.constraints.find((row) => row.name === source.name);
      assert(target && target.type === (CONSTRAINT_TYPES[source.type] ?? source.type) && target.def === source.definition, `tbls constraint differs: ${relation.key}.${source.name}`);
      assert(JSON.stringify(target.columns ?? []) === JSON.stringify(source.columns ?? []), `tbls constraint columns differ: ${relation.key}.${source.name}`);
      if (source.type === 'f') {
        assert(target.referenced_table === relationKey(source.referenced_schema, source.referenced_relation), `tbls FK target differs: ${relation.key}.${source.name}`);
        assert(JSON.stringify(target.referenced_columns ?? []) === JSON.stringify(source.referenced_columns ?? []), `tbls FK target columns differ: ${relation.key}.${source.name}`);
      }
    }
    const expectedIndexes = catalog.indexes.filter((row) => row.schema === relation.schema && row.relation === relation.name);
    assert((table.indexes ?? []).length === expectedIndexes.length, `tbls index set size differs for ${relation.key}`);
  }
  const foreignKeys = catalog.constraints.filter((row) => row.type === 'f');
  assert((schema.relations ?? []).length === foreignKeys.length, 'tbls FK relation set size differs');
  return true;
}

export async function verifyVendoredSchema(path) {
  const bytes = await readFile(path);
  assert(sha256(bytes) === CONFIG.tbls.schemaSha256, 'vendored tbls schema checksum differs from the pinned v1.97.0 copy');
  const schema = JSON.parse(bytes);
  assert(schema.$ref === '#/$defs/Schema' && schema.$defs?.Table && schema.$defs?.Column && schema.$defs?.Constraint, 'vendored tbls schema shape is incomplete');
  return schema;
}
